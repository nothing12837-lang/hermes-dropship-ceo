/**
 * Returns authentic images for a product.
 * If curated multi-angle photos exist, returns those.
 * Otherwise returns explicitImages or primaryUrl.
 * ZERO random stock fillers.
 */
export function resolveProductImages(
  id: string,
  primaryUrl?: string | null,
  category?: string,
  explicitImages?: string[] | null
): string[] {
  // 1. Direct key match in curated galleries
  if (CURATED_PRODUCT_GALLERIES[id] && CURATED_PRODUCT_GALLERIES[id].length > 0) {
    return CURATED_PRODUCT_GALLERIES[id];
  }

  // 2. Substring or slug match
  const matchedKey = Object.keys(CURATED_PRODUCT_GALLERIES).find(
    (k) => id.includes(k) || k.includes(id)
  );
  if (matchedKey && CURATED_PRODUCT_GALLERIES[matchedKey].length > 0) {
    return CURATED_PRODUCT_GALLERIES[matchedKey];
  }

  // 3. Explicit images passed from catalog/DB
  if (Array.isArray(explicitImages) && explicitImages.length > 0) {
    const valid = explicitImages.filter((u) => Boolean(u && u.trim().length > 0));
    if (valid.length > 0) return valid;
  }

  // 4. Primary product URL alone (clean single image, no fake filler stock photos)
  if (primaryUrl && primaryUrl.trim().length > 0) {
    return [primaryUrl.trim()];
  }

  return [];
}
